class Command(BaseCommand):
    help = "Add/update ParkMate's built-in verified and mapped parking locations"

    def handle(self, *args, **options):
        checked = timezone.now()
        verified_created = 0
        verified_updated = 0
        mapped_created = 0
        mapped_updated = 0

        for item in LOCATIONS:
            obj, created = ParkingLocation.objects.update_or_create(
                name=item["name"],
                postcode=item["postcode"],
                defaults={
                    **item,
                    "council_verified": True,
                    "last_checked": checked,
                    "is_active": True,
                },
            )
            obj.full_clean()
            obj.save()
            verified_created += int(created)
            verified_updated += int(not created)

        for item in MAPPED_LOCATIONS:
            obj, created = ParkingLocation.objects.update_or_create(
                name=item["name"],
                address=item["address"],
                defaults={
                    **item,
                    "council_verified": False,
                    "last_checked": None,
                    "is_active": True,
                },
            )
            obj.full_clean()
            obj.save()
            mapped_created += int(created)
            mapped_updated += int(not created)

        self.stdout.write(self.style.SUCCESS(
            f"Seed complete: {len(LOCATIONS)} verified locations and "
            f"{len(MAPPED_LOCATIONS)} mapped locations available."
        ))
